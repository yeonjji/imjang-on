/** 카테고리 문항을 stats로 채운다(null이면 숫자 없는 문장). */
export function resolveFaq(category: FaqCategory, stats: FaqStats | null): FaqItem[] {
  return FAQ[category].map((e) => ({
    q: e.q,
    a: typeof e.a === 'function' ? e.a(stats) : e.a,
    ...(e.source ? { source: e.source } : {}),
  }));
}
